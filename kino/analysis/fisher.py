"""Fast shear-precision forecast: a Fisher (Cramer-Rao) bound through the same
forward model as the inference likelihoods.

For a galaxy, instrument and exposure this estimates how well ``(g1, g2)`` can be
measured without running a sampler (a few forward renders instead of thousands), which is
what makes it usable for ranking hundreds of targets over a semester.

Two estimators (``shear_fisher(..., estimator=...)``):

``"cube"`` (default)
    The bound of :class:`kino.inference.likelihood.IFUCubeLikelihood`: the model cube
    ``mu`` (expected electrons, sky + dark baseline included) against the data voxel by
    voxel with ``var = mu + read^2``, ``F_ij = sum dmu_i dmu_j (1/var + 1/(2 var^2)) + F_prior``.
    Unbiased, and it uses the flux image as well as the kinematics.

``"moments"``
    The bound of :class:`kino.inference.likelihood.IFUMomentLikelihood`: derivatives of the
    flux-weighted Vlos and dispersion maps weighted by their delta-method errors. Kept for
    comparison; the moment estimator is noise-biased (below).

Two numbers come out of either: ``sigma_fixed`` (only the shear free -- optimistic) and
``sigma_marginal`` (nuisance parameters free under priors -- what a real fit faces).

What was validated (see ``scripts/validate_fisher_mle.py``, ``scripts/validate_fisher_forecast.py``
and ``notebooks/data/fisher_validation.json``), against maximum-likelihood fits on many noise
realisations:

* **cube**: maximum-likelihood shear unbiased to ~1e-4 and scatter / Fisher = 0.9-1.3, at every
  per-spaxel S/N tested (about 5 to 100), including with inclination, PA and ``v_flat`` free.
* **moments**: scatter / ``sigma_fixed`` = 1.01 at a median valid-spaxel S/N of ~23, 1.28 at ~13,
  2.2-3.6 at ~7; and a noise bias of ~1 sigma per galaxy that grows toward low S/N and that a
  stack does not average away. An analytic second-order bias correction fails below S/N ~ 12.
  ``median_spaxel_snr`` and :data:`LOW_SNR_WARNING` flag the regime.

**What the bound is not.** It is a *statistical* Cramer-Rao bound for a *perfect model*: the data
are generated by the same ``DiscGalaxy`` family the fit assumes, so the data pin the nuisance
parameters (inclination to ~0.1 deg, ...) far below any prior, and the marginal shear precision
comes out 1e-3-1e-2 per galaxy for bright targets. Real galaxies have non-circular motions,
thickness, warps, an uncertain PSF; that sets a floor the bound ignores. Add one with
``forecast_ifu(intrinsic_sigma=...)`` and ``psf_error=``. The bound is also a local, Gaussian
approximation: it says nothing about multi-modal posteriors.
"""

from __future__ import annotations

import dataclasses
from dataclasses import dataclass, field

import astropy.units as u
import numpy as np
from scipy.optimize import least_squares

from kino.analysis.moments import compute_moment_maps
from kino.galaxy import DiscGalaxy
from kino.inference.likelihood import GALAXY_FIELDS
from kino.lensing import apply_shear

#: Central-difference step for each parameter (in the parameter's own units).
DEFAULT_STEPS = {
    "g1": 0.005, "g2": 0.005, "inc": 1.0, "pa": 1.0, "r_e": 0.02, "v_flat": 2.0,
    "x0": 0.02, "y0": 0.02, "v_sys": 5.0, "sigma0": 2.0,
}  # fmt: skip

#: Default 1-sigma priors on nuisance parameters: what imaging + a Tully-Fisher
#: relation would plausibly supply. ``None`` means unconstrained. ``r_e`` is
#: fractional. These are *assumptions* of the forecast -- override them.
DEFAULT_PRIORS: dict[str, float | None] = {
    "inc": 5.0,  # deg
    "pa": 2.0,  # deg
    "r_e": 0.05,  # fractional
    "v_flat": 0.25,  # fractional (toy Tully-Fisher scatter, see kino.inference.priors)
    "x0": 0.05,  # arcsec
    "y0": 0.05,  # arcsec
    "v_sys": None,
    "sigma0": 20.0,  # km/s
}
_FRACTIONAL = {"r_e", "v_flat"}

#: Median per-spaxel line S/N below which the forecast should not be trusted.
#: Measured with fast maximum-likelihood ensembles (see the module docstring):
#: at a median valid-spaxel S/N of ~13 the scatter is 1.3x the Fisher sigma; at
#: a few it is 2-3.6x, and the estimator is biased by ~1-3 sigma.
LOW_SNR_WARNING = 8.0


@dataclass(frozen=True)
class FisherResult:
    """Output of :func:`shear_fisher`.

    Attributes
    ----------
    sigma_fixed : tuple[float, float]
        ``(sigma_g1, sigma_g2)`` with all other parameters known.
    sigma_marginal : tuple[float, float]
        Same, marginalising over the nuisance parameters with their priors.
    covariance : numpy.ndarray
        Full marginal covariance over ``param_names``.
    param_names : list[str]
    n_spaxels : int
        Spaxels that entered the sums.
    line_snr : float
        Whole-field integrated line S/N, ``sum(flux) / sqrt(sum(flux_err^2))``.
    peak_spaxel_snr : float
        Highest single-spaxel line S/N.
    psf_bias : tuple[float, float]
        Cube estimator, when ``psf_error`` was given: the shear bias ``(dg1, dg2)`` that a
        wrong assumed PSF causes (linear model-mismatch formula). NaN otherwise.
    median_spaxel_snr : float
        Median line S/N of the spaxels that enter the sums. Below
        :data:`LOW_SNR_WARNING` the moment estimator's noise bias and
        non-Gaussian errors make the forecast optimistic (see the module
        docstring and ``CLAUDE.md``).
    """

    sigma_fixed: tuple[float, float]
    sigma_marginal: tuple[float, float]
    covariance: np.ndarray
    param_names: list[str]
    n_spaxels: int
    line_snr: float = 0.0
    peak_spaxel_snr: float = 0.0
    median_spaxel_snr: float = 0.0
    psf_bias: tuple[float, float] = (float("nan"), float("nan"))
    meta: dict = field(default_factory=dict)

    def shear_snr(self, g: tuple[float, float], *, marginal: bool = True) -> float:
        """``|g| / sigma`` along the direction of ``g`` (or the mean sigma if ``g = 0``)."""
        cov = self.covariance[:2, :2] if marginal else np.diag(np.square(self.sigma_fixed))
        gv = np.asarray(g, dtype=float)
        norm = float(np.linalg.norm(gv))
        if norm == 0.0:
            return 0.0
        unit = gv / norm
        return norm / float(np.sqrt(unit @ cov @ unit))


def _moments(ifu, galaxy_kwargs, g1, g2, line_flux, line_wavelength, lsf_sigma):
    scene = apply_shear(DiscGalaxy(**galaxy_kwargs), g1, g2)
    cube = ifu.observe(scene, line_flux=line_flux, line_wavelength=line_wavelength, rng=None)
    return compute_moment_maps(
        cube,
        line_wavelength=line_wavelength,
        lsf_sigma=lsf_sigma,
        snr_threshold=0.0,
        subtract_background=ifu.baseline_electrons(),
        check_window=False,
    )


def _shear_fisher_moments(
    ifu,
    galaxy: DiscGalaxy,
    *,
    line_flux: u.Quantity,
    line_wavelength: u.Quantity,
    g: tuple[float, float] = (0.0, 0.0),
    lsf_sigma: u.Quantity | None = None,
    snr_threshold: float = 3.0,
    priors: dict[str, float | None] | None = None,
    steps: dict[str, float] | None = None,
) -> FisherResult:
    """Moment-map Fisher forecast (see :func:`shear_fisher`, ``estimator="moments"``).

    Parameters
    ----------
    ifu : IFU
        Instrument with its exposure, sky and seeing already set.
    galaxy : DiscGalaxy
        The intrinsic galaxy (its geometry is the fiducial point).
    line_flux, line_wavelength : Quantity
        Intrinsic line flux and rest wavelength, as for ``IFU.observe``.
    g : tuple[float, float]
        Fiducial shear at which derivatives are taken.
    lsf_sigma : Quantity (velocity), optional
        Forwarded to the moment maps, as in the likelihood.
    snr_threshold : float
        Flux S/N a spaxel needs to enter, as in the likelihood.
    priors, steps : dict, optional
        Override :data:`DEFAULT_PRIORS` / :data:`DEFAULT_STEPS`. A prior value
        of ``None`` leaves that parameter unconstrained; ``r_e`` and
        ``v_flat`` priors are fractional.
    """
    priors = {**DEFAULT_PRIORS, **(priors or {})}
    steps = {**DEFAULT_STEPS, **(steps or {})}
    base = {f: getattr(galaxy, f) for f in GALAXY_FIELDS}
    nuisance = [p for p in priors if p in GALAXY_FIELDS]
    names = ["g1", "g2", *nuisance]

    fid = _moments(ifu, base, g[0], g[1], line_flux, line_wavelength, lsf_sigma)
    finite = np.isfinite(fid.flux_err) & (fid.flux_err > 0)
    line_snr = float(np.sum(fid.flux[finite]) / np.sqrt(np.sum(fid.flux_err[finite] ** 2)))
    peak_snr = float(np.max(fid.flux[finite] / fid.flux_err[finite]))
    flux_ok = np.isfinite(fid.flux_err) & (fid.flux / fid.flux_err >= snr_threshold)
    valid = (
        flux_ok
        & np.isfinite(fid.vlos_err)
        & np.isfinite(fid.dispersion_err)
        & (fid.vlos_err > 0)
        & (fid.dispersion_err > 0)
    )
    if not valid.any():
        raise ValueError("no spaxel passes the flux S/N threshold -- the target is undetectable")
    inv_v = 1.0 / fid.vlos_err[valid] ** 2
    inv_s = 1.0 / fid.dispersion_err[valid] ** 2

    derivs = []
    for name in names:
        h = steps[name]
        if name in ("g1", "g2"):
            gp = [g[0], g[1]]
            gm = [g[0], g[1]]
            k = 0 if name == "g1" else 1
            gp[k] += h
            gm[k] -= h
            plus = _moments(ifu, base, *gp, line_flux, line_wavelength, lsf_sigma)
            minus = _moments(ifu, base, *gm, line_flux, line_wavelength, lsf_sigma)
            scale = 2 * h
        else:
            step = h * base[name] if name in _FRACTIONAL else h
            kp, km = dict(base), dict(base)
            kp[name] = base[name] + step
            km[name] = base[name] - step
            if name == "inc":  # keep inside DiscGalaxy's [0, 90] domain
                kp[name] = min(kp[name], 90.0)
            plus = _moments(ifu, kp, g[0], g[1], line_flux, line_wavelength, lsf_sigma)
            minus = _moments(ifu, km, g[0], g[1], line_flux, line_wavelength, lsf_sigma)
            scale = kp[name] - km[name]
        dv = ((plus.vlos - minus.vlos) / scale)[valid]
        ds = ((plus.dispersion - minus.dispersion) / scale)[valid]
        derivs.append((np.nan_to_num(dv), np.nan_to_num(ds)))

    n = len(names)
    fisher = np.zeros((n, n))
    for i in range(n):
        for j in range(i, n):
            fisher[i, j] = fisher[j, i] = np.sum(derivs[i][0] * derivs[j][0] * inv_v) + np.sum(
                derivs[i][1] * derivs[j][1] * inv_s
            )

    prior_precision = np.zeros(n)
    for k, name in enumerate(names):
        if name in priors and priors[name] is not None:
            sigma = priors[name] * base[name] if name in _FRACTIONAL else priors[name]
            prior_precision[k] = 1.0 / sigma**2
    # a vanishing ridge keeps free-but-unconstrained parameters (e.g. v_sys) invertible
    ridge = 1e-12 * np.trace(fisher) / n
    cov = np.linalg.inv(fisher + np.diag(prior_precision) + ridge * np.eye(n))
    fixed = np.linalg.inv(fisher[:2, :2] + ridge * np.eye(2))
    return FisherResult(
        sigma_fixed=(float(np.sqrt(fixed[0, 0])), float(np.sqrt(fixed[1, 1]))),
        sigma_marginal=(float(np.sqrt(cov[0, 0])), float(np.sqrt(cov[1, 1]))),
        covariance=cov,
        param_names=names,
        n_spaxels=int(valid.sum()),
        line_snr=line_snr,
        peak_spaxel_snr=peak_snr,
        median_spaxel_snr=float(np.median((fid.flux / fid.flux_err)[valid])),
    )


#: Nuisance priors for the cube-level estimator: the moment-map defaults plus the
#: Sersic index, the rotation-curve turnover radius and the line flux (measured
#: from the spectrum, so known to a few per cent). ``None`` = unconstrained.
DEFAULT_CUBE_PRIORS: dict[str, float | None] = {
    **DEFAULT_PRIORS,
    "sersic_n": 0.3,
    "r_t": 0.2,  # fractional
    "line_flux": 0.05,  # fractional
}
_FRACTIONAL_CUBE = {"r_e", "v_flat", "r_t", "line_flux"}
_VARIANCE_FLOOR = 1e-3  # electrons^2; see kino.inference.likelihood.VARIANCE_FLOOR
_CUBE_STEPS = {**DEFAULT_STEPS, "sersic_n": 0.05, "r_t": 0.02}


def _shear_fisher_cube(
    ifu,
    galaxy: DiscGalaxy,
    *,
    line_flux: u.Quantity,
    line_wavelength: u.Quantity,
    g: tuple[float, float],
    snr_threshold: float,
    priors: dict[str, float | None] | None,
    steps: dict[str, float] | None,
    free: list[str] | None,
    psf_error: float | None,
) -> FisherResult:
    """Voxel-level Fisher matrix: ``F_ij = sum_voxels dmu_i dmu_j (1/var + 1/(2 var^2))``.

    ``mu`` is the model cube (expected electrons, sky + dark baseline included)
    and ``var = mu + read noise^2`` its variance, so this is the Cramer-Rao bound
    of the exact Gaussian/Poisson cube likelihood. It uses every voxel -- flux,
    velocity *and* dispersion information at once, with no moment-map estimator
    (whose noise bias is what limits the moment version). The line flux enters as a
    multiplicative factor with a fractional prior (a spectrum measures it to a few
    per cent); its derivative is analytic (the source part of the cube scales with it).

    Works with either an IFU or a SlitSpectrograph (duck-typed: both expose ``.psf``,
    ``.observe()`` and ``.baseline_electrons()``; a SlitSpectrograph's ``.observe()``
    result is unwrapped to its ``.spectrum`` before use).

    ``psf_error``: the shear bias when the fit assumes ``ifu.psf`` but the data have a
    FWHM larger by that fraction. It is the converged Levenberg-Marquardt solution of
    the mis-specified fit (data rendered with the wrong PSF, fitted with the assumed
    one, priors included), not the linear formula ``F^-1 J^T W dm``, which is off by
    2-3x at high S/N where the mismatch is many sigma.
    """
    priors = {**DEFAULT_CUBE_PRIORS, **(priors or {})}
    steps = {**_CUBE_STEPS, **(steps or {})}
    base = {f: getattr(galaxy, f) for f in GALAXY_FIELDS}
    nuisance = [p for p in priors if p in GALAXY_FIELDS or p == "line_flux"]
    if free is not None:
        unknown = [p for p in free if p not in nuisance]
        if unknown:
            raise ValueError(f"free parameters not in the prior set: {unknown}")
        nuisance = [p for p in nuisance if p in free]
    names = ["g1", "g2", *nuisance]
    baseline = ifu.baseline_electrons()

    # parameter vector: shear, galaxy fields, and ``line_flux`` as a multiplicative factor
    theta0 = np.array([g[0], g[1]] + [1.0 if n == "line_flux" else base[n] for n in names[2:]])

    def render(instrument, theta):
        kwargs = dict(base)
        factor = 1.0
        for n, v in zip(names[2:], theta[2:], strict=True):
            if n == "line_flux":
                factor = v
            else:
                kwargs[n] = float(v)
        kwargs["inc"] = min(max(kwargs["inc"], 0.0), 90.0)
        kwargs["sersic_n"] = max(kwargs["sersic_n"], 0.2)
        scene = apply_shear(DiscGalaxy(**kwargs), theta[0], theta[1])
        result = instrument.observe(
            scene, line_flux=line_flux * factor, line_wavelength=line_wavelength, rng=None
        )
        # a SlitSpectrograph returns a SlitObservation; only its .spectrum enters the fit
        # (the companion broadband image is a placement aid, not photometrically fit)
        return getattr(result, "spectrum", result)

    def step_for(k):
        n = names[k]
        if n in ("g1", "g2") or n == "line_flux":
            return steps.get(n, 0.005) if n != "line_flux" else 0.01
        h = steps.get(n, 0.02)
        return h * theta0[k] if n in _FRACTIONAL_CUBE else h

    def jacobian(instrument, theta):
        cube = render(instrument, theta)
        signal = cube.flux - baseline
        cols = []
        for k, n in enumerate(names):
            if n == "line_flux":
                cols.append(signal / theta[k])  # d mu / d factor
                continue
            h = step_for(k)
            tp, tm = theta.copy(), theta.copy()
            tp[k] += h
            tm[k] -= h
            cols.append((render(instrument, tp).flux - render(instrument, tm).flux) / (2 * h))
        return cube, cols

    fid, derivs = jacobian(ifu, theta0)
    mu, var = fid.flux, np.maximum(fid.variance, _VARIANCE_FLOOR)
    signal = mu - baseline
    spaxel_snr = signal.sum(axis=0) / np.sqrt(var.sum(axis=0))
    used = spaxel_snr >= snr_threshold
    if not used.any():
        raise ValueError("no spaxel passes the flux S/N threshold -- the target is undetectable")

    def information(cols, variance):
        variance = np.maximum(variance, _VARIANCE_FLOOR)
        w = 1.0 / variance + 0.5 / variance**2
        n = len(cols)
        f = np.zeros((n, n))
        for i in range(n):
            for j in range(i, n):
                f[i, j] = f[j, i] = float(np.sum(cols[i] * cols[j] * w))
        return f, w

    fisher, weight = information(derivs, var)
    n = len(names)
    prior_precision = np.zeros(n)
    for k, name in enumerate(names):
        pv = priors.get(name)
        if pv is None:
            continue
        sigma = pv * theta0[k] if name in _FRACTIONAL_CUBE and name != "line_flux" else pv
        prior_precision[k] = 1.0 / sigma**2
    ridge = 1e-12 * np.trace(fisher) / n
    cov = np.linalg.inv(fisher + np.diag(prior_precision) + ridge * np.eye(n))
    fixed = np.linalg.inv(fisher[:2, :2] + ridge * np.eye(2))

    psf_bias = (float("nan"), float("nan"))
    if psf_error is not None:
        wrong = dataclasses.replace(
            ifu, psf=dataclasses.replace(ifu.psf, seeing_fwhm=ifu.psf.seeing_fwhm * (1 + psf_error))
        )
        data = render(wrong, theta0).flux  # the truth, seen through the larger PSF
        scale = np.array([step_for(k) for k in range(n)])
        root_prior = np.sqrt(prior_precision)

        def residuals(x):
            theta = theta0 + x * scale
            cube = render(ifu, theta)
            return np.concatenate(
                [
                    ((data - cube.flux) / np.sqrt(cube.variance)).ravel(),
                    root_prior * (theta - theta0),
                ]
            )

        sol = least_squares(
            residuals, np.zeros(n), method="lm", diff_step=0.25, xtol=1e-10, ftol=1e-12
        )
        shift = sol.x * scale
        psf_bias = (float(shift[0]), float(shift[1]))

    total = signal.sum(axis=0)
    return FisherResult(
        sigma_fixed=(float(np.sqrt(fixed[0, 0])), float(np.sqrt(fixed[1, 1]))),
        sigma_marginal=(float(np.sqrt(cov[0, 0])), float(np.sqrt(cov[1, 1]))),
        covariance=cov,
        param_names=names,
        n_spaxels=int(used.sum()),
        line_snr=float(total.sum() / np.sqrt(var.sum())),
        peak_spaxel_snr=float(np.max(spaxel_snr)),
        median_spaxel_snr=float(np.median(spaxel_snr[used])),
        psf_bias=psf_bias,
        meta={"estimator": "cube"},
    )


def shear_fisher(
    ifu,
    galaxy: DiscGalaxy,
    *,
    line_flux: u.Quantity,
    line_wavelength: u.Quantity,
    g: tuple[float, float] = (0.0, 0.0),
    estimator: str = "cube",
    lsf_sigma: u.Quantity | None = None,
    snr_threshold: float = 3.0,
    priors: dict[str, float | None] | None = None,
    steps: dict[str, float] | None = None,
    free: list[str] | None = None,
    psf_error: float | None = None,
) -> FisherResult:
    """Fisher forecast of ``(g1, g2)`` precision for ``galaxy`` seen through ``ifu``.

    Parameters
    ----------
    ifu : IFU or SlitSpectrograph
        Instrument with its exposure, sky and seeing already set. The ``"cube"``
        estimator works with either (its :class:`IFUCubeLikelihood` or
        :class:`SlitCubeLikelihood` counterpart); ``"moments"`` is IFU-only.
    galaxy : DiscGalaxy
        The intrinsic galaxy (its geometry is the fiducial point).
    line_flux, line_wavelength : Quantity
        Intrinsic line flux and rest wavelength, as for ``IFU.observe``.
    g : tuple[float, float]
        Fiducial shear at which derivatives are taken.
    estimator : {"cube", "moments"}
        ``"cube"`` (default): the Cramer-Rao bound of the voxel-level cube
        likelihood -- unbiased, and it uses the flux image as well as the
        kinematics; works for an IFU or a SlitSpectrograph. ``"moments"``: the
        flux-weighted velocity/dispersion moment maps of ``IFUMomentLikelihood``
        -- IFU only, kept for comparison; its estimator has a noise bias at low
        S/N (see the module docstring).
    lsf_sigma : Quantity (velocity), optional
        Moment estimator only.
    snr_threshold : float
        Per-spaxel S/N a spaxel needs to enter (cube: only for the reported
        ``n_spaxels``/``median_spaxel_snr``; the sums use every voxel).
    priors, steps : dict, optional
        Override the default nuisance priors (:data:`DEFAULT_CUBE_PRIORS` /
        :data:`DEFAULT_PRIORS`) and difference steps. A prior of ``None``
        leaves that parameter unconstrained; ``r_e``, ``v_flat`` (and, for the
        cube, ``r_t`` and ``line_flux``) priors are fractional.
    free : list[str], optional
        Cube estimator only: restrict the free nuisance parameters to this
        subset of the prior keys (the rest are held at their fiducial values).
        Default: all of them.
    psf_error : float, optional
        Cube estimator only: fractional error on the assumed PSF FWHM (truth larger by
        this fraction). Fills :attr:`FisherResult.psf_bias`.
    """
    if estimator == "cube":
        return _shear_fisher_cube(
            ifu, galaxy, line_flux=line_flux, line_wavelength=line_wavelength, g=g,
            snr_threshold=snr_threshold, priors=priors, steps=steps, free=free,
            psf_error=psf_error,
        )  # fmt: skip
    if estimator == "moments":
        return _shear_fisher_moments(
            ifu, galaxy, line_flux=line_flux, line_wavelength=line_wavelength, g=g,
            lsf_sigma=lsf_sigma, snr_threshold=snr_threshold, priors=priors, steps=steps,
        )  # fmt: skip
    raise ValueError(f"estimator must be 'cube' or 'moments', got {estimator!r}")
