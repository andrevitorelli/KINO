"""Cross-check kino.galaxy.DiscGalaxy against an independent KinMS cube.

tests/galaxy/test_disc.py::test_pa_zero_redshifted_side_matches_kinms_convention
pins the sign at two points; this test goes further and checks the whole
Vlos *map* shape agrees with a cube generated by the independent KinMS
implementation (kino.io.kinms), closing the cross-check that
kino/io/kinms.py's module docstring flags as needed once kino.galaxy exists.
Requires the optional `kinms` package (the `data` extra).
"""

import astropy.units as u
import numpy as np
import pytest

pytest.importorskip("kinms")

from kino.galaxy.disc import DiscGalaxy  # noqa: E402
from kino.galaxy.rotation_curve import arctan  # noqa: E402
from kino.io.kinms import generate_disc_cube  # noqa: E402


def test_vlos_map_agrees_with_independent_kinms_cube():
    inc, pa, v_flat, r_t = 60.0, 40.0, 180.0, 3.0
    pixel_scale = 1.0  # arcsec

    gal = DiscGalaxy(r_e=3.0, inc=inc, pa=pa, v_flat=v_flat, r_t=r_t, rotation_curve="arctan")

    vel_rad = np.linspace(0, 15, 30)
    cube = generate_disc_cube(
        field_of_view=30 * u.arcsec,
        pixel_scale=pixel_scale * u.arcsec,
        velocity_range=500 * u.km / u.s,
        channel_width=10 * u.km / u.s,
        beam_size=1 * u.arcsec,
        inc=inc,
        pa=pa,
        sb_rad=[0, 5, 10, 15] * u.arcsec,
        sb_prof=[1.0, 0.6, 0.2, 0.0],
        vel_rad=vel_rad * u.arcsec,
        vel_prof=arctan(vel_rad, v_flat, r_t) * u.km / u.s,
        gas_sigma=5 * u.km / u.s,
        n_clouds=300_000,
        rng=np.random.default_rng(3),
    )

    v = cube.spectral_axis.to_value(u.km / u.s)[:, None, None]
    flux_map = cube.flux.sum(axis=0)
    with np.errstate(invalid="ignore", divide="ignore"):
        vel_map_kinms = (cube.flux * v).sum(axis=0) / flux_map
    signal = flux_map > 0.1 * flux_map.max()
    assert signal.sum() > 20  # sanity: the mock actually has a resolved disc in it

    ny, nx = flux_map.shape
    coords = (np.arange(nx) - nx // 2) * pixel_scale
    x_grid, y_grid = np.meshgrid(coords, coords)
    vel_map_analytic = gal.vlos(x_grid, y_grid)

    kinms_vals = vel_map_kinms[signal]
    analytic_vals = vel_map_analytic[signal]
    correlation = np.corrcoef(kinms_vals, analytic_vals)[0, 1]

    assert correlation > 0.99
    assert np.mean(np.abs(kinms_vals - analytic_vals)) < 0.15 * np.std(kinms_vals)
